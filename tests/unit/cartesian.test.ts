import { describe, it } from "node:test";
import assert from "node:assert/strict";
import {
  cartesianProduct,
  generateBarcode,
  generateVariantMatrix,
} from "../../src/lib/utils/cartesian";

describe("Cartesian Product & Barcode Engine", () => {
  describe("cartesianProduct()", () => {
    it("should compute exact combinations for a 2-axis matrix (Size x Color)", () => {
      const axes = [
        { name: "Size", values: ["S", "M", "L"] },
        { name: "Color", values: ["Red", "Blue"] },
      ];
      const result = cartesianProduct(axes);

      assert.equal(result.length, 6);
      assert.deepEqual(result, [
        { Size: "S", Color: "Red" },
        { Size: "S", Color: "Blue" },
        { Size: "M", Color: "Red" },
        { Size: "M", Color: "Blue" },
        { Size: "L", Color: "Red" },
        { Size: "L", Color: "Blue" },
      ]);
    });

    it("should compute combinations for a 3-axis matrix (Size x Color x Fit)", () => {
      const axes = [
        { name: "Size", values: ["Small", "Large"] },
        { name: "Color", values: ["Black", "White"] },
        { name: "Fit", values: ["Slim", "Regular"] },
      ];
      const result = cartesianProduct(axes);

      assert.equal(result.length, 8);
      assert.deepEqual(result[0], { Size: "Small", Color: "Black", Fit: "Slim" });
      assert.deepEqual(result[7], { Size: "Large", Color: "White", Fit: "Regular" });
    });

    it("should handle a single axis gracefully", () => {
      const axes = [{ name: "Storage", values: ["128GB", "256GB", "512GB"] }];
      const result = cartesianProduct(axes);

      assert.equal(result.length, 3);
      assert.deepEqual(result, [
        { Storage: "128GB" },
        { Storage: "256GB" },
        { Storage: "512GB" },
      ]);
    });

    it("should return empty array for empty axes input", () => {
      assert.deepEqual(cartesianProduct([]), []);
      assert.deepEqual(cartesianProduct([{ name: "Empty", values: [] }]), []);
    });
  });

  describe("generateBarcode() EAN-13 Checksum Validation", () => {
    it("should generate a 13-digit barcode with valid GS1 mathematical checksum", () => {
      const barcode = generateBarcode("PRD", 101);

      assert.equal(barcode.length, 13);
      assert.equal(/^\d{13}$/.test(barcode), true);

      // Verify EAN-13 Checksum Algorithm:
      // Sum of digits in odd positions * 1 + sum of digits in even positions * 3
      // Checksum = (10 - (sum % 10)) % 10
      const digits = barcode.split("").map(Number);
      const dataDigits = digits.slice(0, 12);
      const checksumDigit = digits[12];

      let sum = 0;
      for (let i = 0; i < 12; i++) {
        sum += i % 2 === 0 ? dataDigits[i] : dataDigits[i] * 3;
      }
      const calculatedChecksum = (10 - (sum % 10)) % 10;

      assert.equal(checksumDigit, calculatedChecksum);
    });
  });

  describe("generateVariantMatrix()", () => {
    it("should generate typed variant combinations with autogenerated SKUs and barcodes", () => {
      const variantAxes = [
        { name: "Size", values: ["S", "M"] },
        { name: "Color", values: ["Navy", "Grey"] },
      ];

      const combinations = generateVariantMatrix("TSHIRT", 999, variantAxes);

      assert.equal(combinations.length, 4);
      assert.equal(combinations[0].title, "S / Navy");
      assert.equal(combinations[0].sku, "TSHIRT-S-NAVY");
      assert.equal(combinations[0].price, 999);
      assert.equal(combinations[0].barcode.length, 13);
      assert.deepEqual(combinations[0].optionValues, {
        Size: "S",
        Color: "Navy",
      });
    });
  });
});
